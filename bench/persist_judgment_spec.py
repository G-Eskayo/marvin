#!/usr/bin/env python3
"""persist_judgment_spec.py — write spec_search results to config/judgment_spec.json

Takes the output of spec_search.py and persists the winning setup to a location
that logic_auditor.py (or its wrapper) can read at judgment time.

Usage:
    python3 spec_search.py ... | python3 persist_judgment_spec.py

Or as a separate step:
    python3 persist_judgment_spec.py --result spec_search_result.json

Once persisted, logic_auditor.py should be updated to read from judgment_spec.json
instead of hardcoding JUDGMENT_MODEL and _JUDGMENT_PROMPTS. This makes the
tuned result live, not just a report nobody consumes (Watts check).
"""
from __future__ import annotations
import json
import sys
from pathlib import Path
from datetime import datetime, timezone
import argparse


def persist_judgment_spec(result: dict, output_path: Path = None) -> None:
    """Persist spec_search result to judgment_spec.json.

    result: output from spec_search.py {"best_setup": ..., "best_metrics": ...}
    output_path: where to write (default: skills/paper-dive/config/judgment_spec.json)
    """
    if output_path is None:
        root = Path(__file__).resolve().parent.parent
        output_path = root / "skills" / "paper-dive" / "config" / "judgment_spec.json"

    output_path.parent.mkdir(parents=True, exist_ok=True)

    best_setup = result.get("best_setup", {})
    best_metrics = result.get("best_metrics", {})
    accuracy = best_metrics.get("accuracy", {}).get("value")

    # Read baseline for comparison
    baseline_accuracy = None

    spec = {
        "description": "Tuned judgment spec for logic_auditor.py. Built by spec_search.py",
        "timestamp": datetime.now(timezone.utc).isoformat(),
        "model": best_setup.get("model", "qwen2.5:3b"),
        "temperature": best_setup.get("temperature", 0.7),
        "prompt_variant": best_setup.get("prompt_variant", "default"),
        "num_ctx": best_setup.get("num_ctx", 2048),
        "accuracy": accuracy,
        "baseline_accuracy": baseline_accuracy,
        "accuracy_relative_improvement": None,
        "cost_vs_baseline": "$0 local vs Claude per-call cost",
        "edits_accepted": result.get("edits_accepted", 0),
        "rounds_completed": result.get("rounds_completed", 0),
        "notes": "This file is generated by the spec_search pipeline. Edit only if manually tuning."
    }

    # Write atomically
    tmp = output_path.with_suffix(".tmp")
    tmp.write_text(json.dumps(spec, indent=2))
    tmp.replace(output_path)

    print(f"Persisted judgment spec to {output_path}", file=sys.stderr)
    print(json.dumps(spec, indent=2), file=sys.stdout)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--result", help="path to spec_search result JSON (stdin if not provided)")
    ap.add_argument("--output", help="where to write judgment_spec.json")
    args = ap.parse_args()

    # Load result
    if args.result:
        result_path = Path(args.result)
        if not result_path.exists():
            sys.exit(f"Result file not found: {result_path}")
        result = json.loads(result_path.read_text())
    else:
        # Read from stdin
        result_text = sys.stdin.read()
        try:
            result = json.loads(result_text)
        except json.JSONDecodeError as e:
            sys.exit(f"Failed to parse JSON from stdin: {e}")

    # Persist
    output_path = Path(args.output) if args.output else None
    persist_judgment_spec(result, output_path)


if __name__ == "__main__":
    main()
