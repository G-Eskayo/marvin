"""Regression (2026-10-06): a symlink named dashboard/node_modules was committed (git add -A in a worktree where node_modules was
linked to the main checkout's). "node_modules/" in .gitignore matches directories only, so the link was tracked, and the next pull
replaced the real directory with a link to itself on both machines."""
import subprocess
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]


def test_node_modules_is_never_tracked():
    out = subprocess.run(["git", "ls-files", "--", "dashboard/node_modules", "node_modules"], cwd=REPO, capture_output=True, text=True).stdout
    assert out.strip() == "", f"node_modules is tracked: {out.strip()}"


def test_gitignore_covers_node_modules_as_a_file_too():
    ignored = subprocess.run(["git", "check-ignore", "dashboard/node_modules"], cwd=REPO, capture_output=True, text=True)
    assert ignored.returncode == 0, "dashboard/node_modules (as a symlink/file) must be ignored"
