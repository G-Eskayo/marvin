"""node_modules_seed (#687): a worktree gets its dependencies as a copy-on-write clone of a cached install, not a fresh
`npm install` (~0.8 GB written each time on the Mac mini). Real files, real `cp`, temp dirs only. Run via:
    ~/.agents/venv/bin/python -m pytest lib/tests/test_node_modules_seed.py -v
"""
from __future__ import annotations

import json
import sys
import threading
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import node_modules_seed as nms  # noqa: E402


def _project(root: Path, lock: dict | None = None) -> Path:
    """A project dir with a lockfile, as `npm install` would leave it before node_modules exists."""
    root.mkdir(parents=True, exist_ok=True)
    (root / "package-lock.json").write_text(json.dumps(lock or {"lockfileVersion": 3, "packages": {"": {}}}))
    return root


def _install(project: Path, marker: str = "v1") -> None:
    """Stand-in for a finished `npm install`: a nested tree, a hidden lockfile and a symlink, like the real thing."""
    nm = project / "node_modules"
    (nm / "left-pad" / "lib").mkdir(parents=True)
    (nm / "left-pad" / "lib" / "index.js").write_text(f"module.exports = '{marker}'\n")
    (nm / ".package-lock.json").write_text("{}")
    (nm / ".bin").mkdir()
    (nm / ".bin" / "left-pad").symlink_to("../left-pad/lib/index.js")


@pytest.fixture
def cache(tmp_path):
    return tmp_path / "cache"


@pytest.fixture(autouse=True)
def _fixed_runtime(monkeypatch):
    monkeypatch.setattr(nms, "_runtime", lambda: "node-v22.0.0-darwin-arm64")


def test_a_cold_cache_seeds_nothing(tmp_path, cache):
    p = _project(tmp_path / "wt")
    assert nms.seed(p, cache_root=cache) is False
    assert not (p / "node_modules").exists()


def test_store_then_seed_gives_a_fresh_worktree_the_same_install(tmp_path, cache):
    first = _project(tmp_path / "a")
    _install(first)
    assert nms.store(first, cache_root=cache) is True
    second = _project(tmp_path / "b")
    assert nms.seed(second, cache_root=cache) is True
    assert (second / "node_modules" / "left-pad" / "lib" / "index.js").read_text() == "module.exports = 'v1'\n"
    assert (second / "node_modules" / ".package-lock.json").exists()  # npm's own record that the tree is installed
    assert (second / "node_modules" / ".bin" / "left-pad").is_symlink()  # links survive as links, not copies


def test_a_seeded_tree_is_independent_of_the_cache(tmp_path, cache):
    a = _project(tmp_path / "a"); _install(a); nms.store(a, cache_root=cache)
    b = _project(tmp_path / "b"); nms.seed(b, cache_root=cache)
    (b / "node_modules" / "left-pad" / "lib" / "index.js").write_text("tampered")
    c = _project(tmp_path / "c"); nms.seed(c, cache_root=cache)
    assert (c / "node_modules" / "left-pad" / "lib" / "index.js").read_text() == "module.exports = 'v1'\n"


def test_a_changed_lockfile_misses(tmp_path, cache):
    a = _project(tmp_path / "a"); _install(a); nms.store(a, cache_root=cache)
    b = _project(tmp_path / "b", lock={"lockfileVersion": 3, "packages": {"node_modules/left-pad": {"version": "2.0.0"}}})
    assert nms.seed(b, cache_root=cache) is False
    assert not (b / "node_modules").exists()


def test_a_different_node_version_or_machine_misses(tmp_path, cache, monkeypatch):
    a = _project(tmp_path / "a"); _install(a); nms.store(a, cache_root=cache)
    monkeypatch.setattr(nms, "_runtime", lambda: "node-v24.1.0-darwin-arm64")  # native addons are built per Node ABI
    b = _project(tmp_path / "b")
    assert nms.seed(b, cache_root=cache) is False


def test_an_existing_node_modules_is_never_overwritten(tmp_path, cache):
    a = _project(tmp_path / "a"); _install(a, "cached"); nms.store(a, cache_root=cache)
    b = _project(tmp_path / "b"); _install(b, "mine")
    assert nms.seed(b, cache_root=cache) is False
    assert (b / "node_modules" / "left-pad" / "lib" / "index.js").read_text() == "module.exports = 'mine'\n"


def test_no_lockfile_means_no_seed_and_no_store(tmp_path, cache):
    p = tmp_path / "bare"; p.mkdir(); _install(p)
    assert nms.store(p, cache_root=cache) is False
    q = tmp_path / "bare2"; q.mkdir()
    assert nms.seed(q, cache_root=cache) is False
    assert not cache.exists() or not any(cache.iterdir())


def test_store_without_an_install_stores_nothing(tmp_path, cache):
    p = _project(tmp_path / "a")
    assert nms.store(p, cache_root=cache) is False


def test_store_is_idempotent(tmp_path, cache):
    a = _project(tmp_path / "a"); _install(a)
    assert nms.store(a, cache_root=cache) is True
    assert nms.store(a, cache_root=cache) is False  # already cached: nothing written the second time
    assert len([d for d in cache.iterdir() if not d.name.startswith(".")]) == 1


def test_a_half_written_entry_is_a_miss_not_a_broken_seed(tmp_path, cache):
    a = _project(tmp_path / "a"); _install(a); nms.store(a, cache_root=cache)
    entry = nms.entry_path(a, cache_root=cache)
    (entry / nms.COMPLETE).unlink()  # as if the store was killed before it finished
    b = _project(tmp_path / "b")
    assert nms.seed(b, cache_root=cache) is False
    assert not (b / "node_modules").exists()


def test_concurrent_stores_leave_exactly_one_complete_entry(tmp_path, cache):
    projects = []
    for i in range(6):
        p = _project(tmp_path / f"p{i}"); _install(p); projects.append(p)
    results = []
    threads = [threading.Thread(target=lambda p=p: results.append(nms.store(p, cache_root=cache))) for p in projects]
    for t in threads: t.start()
    for t in threads: t.join()
    entries = [d for d in cache.iterdir() if not d.name.startswith(".")]
    assert len(entries) == 1 and (entries[0] / nms.COMPLETE).exists()
    assert results.count(True) == 1
    assert not [d for d in cache.iterdir() if d.name.startswith(".")]  # no temp dirs left behind
    b = _project(tmp_path / "b")
    assert nms.seed(b, cache_root=cache) is True


def test_the_cache_keeps_only_the_newest_entries(tmp_path, cache):
    for i in range(nms.KEEP + 2):
        p = _project(tmp_path / f"p{i}", lock={"lockfileVersion": 3, "n": i}); _install(p)
        assert nms.store(p, cache_root=cache) is True
    entries = [d for d in cache.iterdir() if not d.name.startswith(".")]
    assert len(entries) == nms.KEEP
    newest = _project(tmp_path / "again", lock={"lockfileVersion": 3, "n": nms.KEEP + 1})
    assert nms.seed(newest, cache_root=cache) is True
    oldest = _project(tmp_path / "old", lock={"lockfileVersion": 3, "n": 0})
    assert nms.seed(oldest, cache_root=cache) is False


def test_seed_never_raises_on_a_broken_cache(tmp_path, cache):
    cache.mkdir(parents=True)
    a = _project(tmp_path / "a")
    nms.entry_path(a, cache_root=cache).write_text("not a directory")
    assert nms.seed(a, cache_root=cache) is False


def test_cli_seed_and_store(tmp_path, cache, capsys):
    a = _project(tmp_path / "a"); _install(a)
    assert nms.main(["store", str(a), "--cache", str(cache)]) == 0
    b = _project(tmp_path / "b")
    assert nms.main(["seed", str(b), "--cache", str(cache)]) == 0
    assert "seeded" in capsys.readouterr().out
    assert (b / "node_modules" / "left-pad").is_dir()


# ── npm_install / seed_tree: the one call every install site uses ───────────────────────────────────────────────────

class _FakeNpm:
    """Records calls; on 'install' it builds a node_modules tree only when none is there (like npm's no-op)."""
    def __init__(self, ok: bool = True):
        self.calls, self.ok = [], ok

    def __call__(self, cmd, cwd=None, **kw):
        import subprocess as sp
        self.calls.append((list(cmd), Path(cwd)))
        if self.ok and not (Path(cwd) / "node_modules").exists():
            _install(Path(cwd), "from-npm")
        return sp.CompletedProcess(cmd, 0 if self.ok else 1, "", "" if self.ok else "npm ERR! boom")


def test_npm_install_on_a_cold_cache_installs_then_stores(tmp_path, cache):
    p = _project(tmp_path / "a")
    npm = _FakeNpm()
    proc = nms.npm_install(p, ["npm", "install"], cache_root=cache, run=npm)
    assert proc.returncode == 0 and npm.calls == [(["npm", "install"], p)]
    q = _project(tmp_path / "b")
    assert nms.seed(q, cache_root=cache) is True  # the install was cached


def test_npm_install_on_a_warm_cache_seeds_first_so_npm_finds_it_installed(tmp_path, cache):
    a = _project(tmp_path / "a"); _install(a, "cached"); nms.store(a, cache_root=cache)
    b = _project(tmp_path / "b")
    npm = _FakeNpm()
    nms.npm_install(b, ["npm", "install"], cache_root=cache, run=npm)
    assert (b / "node_modules" / "left-pad" / "lib" / "index.js").read_text() == "module.exports = 'cached'\n"
    assert len(npm.calls) == 1  # npm still runs (it verifies the tree), it just has nothing to write


def test_a_failed_install_is_never_cached(tmp_path, cache):
    p = _project(tmp_path / "a")
    _install(p, "half")  # what a failed npm leaves behind
    proc = nms.npm_install(p, ["npm", "install"], cache_root=cache, run=_FakeNpm(ok=False))
    assert proc.returncode == 1
    assert not cache.exists() or not [d for d in cache.iterdir() if not d.name.startswith(".")]


def test_seed_tree_seeds_every_project_in_a_new_worktree_and_nothing_else(tmp_path, cache):
    src = _project(tmp_path / "src" / "dashboard"); _install(src); nms.store(src, cache_root=cache)
    wt = tmp_path / "wt"
    _project(wt / "dashboard")
    (wt / "docs").mkdir(parents=True)
    _project(wt / "dashboard" / "node_modules_like_but_not")  # a different lockfile: misses, untouched
    (wt / "dashboard" / "node_modules_like_but_not" / "package-lock.json").write_text('{"other": 1}')
    seeded = nms.seed_tree(wt, cache_root=cache)
    assert seeded == [wt / "dashboard"]
    assert (wt / "dashboard" / "node_modules" / "left-pad").is_dir()
    assert not (wt / "docs" / "node_modules").exists()


def test_seed_tree_never_descends_into_node_modules(tmp_path, cache):
    wt = tmp_path / "wt"
    p = _project(wt / "dashboard"); _install(p)
    _project(p / "node_modules" / "left-pad")  # packages ship lockfiles too; seeding inside node_modules is wrong
    assert nms.seed_tree(wt, cache_root=cache) == []
