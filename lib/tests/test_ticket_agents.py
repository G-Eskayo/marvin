def iso(days_ago=0.0):
    return (NOW - timedelta(days=days_ago)).isoformat()


def issue(n, labels=(), body="", title="Ticket", created=1, updated=0.1):
    return {"number": n, "title": title, "labels": [{"name": l} for l in labels], "body": body,
            "createdAt": iso(created), "updatedAt": iso(updated)}


def ops(actions, **match):
    return [a for a in actions if all(a.get(k) == v for k, v in match.items())]


