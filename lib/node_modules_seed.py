#!/usr/bin/env python3
"""node_modules_seed.py — give a fresh worktree its node_modules as a copy-on-write clone of a cached install (#687).

On 2026-10-26 the ticket pipeline wrote 137 GB in 17 hours on the Mac mini and filled its disk. Every ticket worktree,
merge-gate copy and conflict repair ran its own `npm install` of the dashboard: ~0.8 GB of disk traffic and 616 MB of
space each. A clone (APFS `cp -c`, `cp --reflink` on Linux) shares the cache's blocks, so seeding writes almost nothing
and costs almost no space, however many worktrees hold one.

    seed(project)   before an install: clone the cached tree in, when one matches. Never touches an existing
                    node_modules, never raises; a miss just means npm installs as before.
    store(project)  after a successful install: clone the result into the cache (temp dir, then an atomic rename),
                    unless that entry already exists.

The key is the project's package-lock.json plus the Node version, OS and CPU (native addons are built per Node ABI), so
a changed lockfile or toolchain always gets a real install. An entry counts only once its COMPLETE marker is written.
Space: at most KEEP entries (oldest removed on store), and each worktree's clone shares their blocks. Time: one hash of
the lockfile per call, one clone per seed.

CLI (for the merge gate, which is JavaScript):
    node_modules_seed.py seed  <project-dir> [--cache DIR]
    node_modules_seed.py store <project-dir> [--cache DIR]
Both exit 0 whatever happens; this is an optimization, not a step that can fail a run.
"""
from __future__ import annotations

import argparse
import hashlib
import os
import platform
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

CACHE_ROOT = Path.home() / ".cache" / "marvin" / "node_modules"
KEEP = 3
COMPLETE = ".complete"
LOCKFILE = "package-lock.json"


def _runtime() -> str:
    try:
        node = subprocess.run(["node", "--version"], capture_output=True, text=True, timeout=10).stdout.strip()
    except (OSError, subprocess.SubprocessError):
        node = "no-node"
    return f"node-{node or 'unknown'}-{sys.platform}-{platform.machine()}"


def _key(project: Path) -> str | None:
    lock = Path(project) / LOCKFILE
    try:
        data = lock.read_bytes()
    except OSError:
        return None
    return hashlib.sha256(data + b"\0" + _runtime().encode()).hexdigest()[:24]


def entry_path(project: Path, cache_root: Path | None = None) -> Path:
    key = _key(project)
    if key is None:
        raise FileNotFoundError(f"no {LOCKFILE} in {project}")
    return Path(cache_root or CACHE_ROOT) / key


def _clone(src: Path, dest: Path) -> None:
    """Copy-on-write when the filesystem can (APFS, btrfs/xfs), a plain copy otherwise. Symlinks stay symlinks."""
    if sys.platform == "darwin":
        cmd = ["cp", "-cRP", str(src), str(dest)]
    else:
        cmd = ["cp", "-a", "--reflink=auto", str(src), str(dest)]
    subprocess.run(cmd, check=True, capture_output=True, timeout=600)


def seed(project: Path, cache_root: Path | None = None) -> bool:
    """Clone the cached node_modules into `project`. True only when it did."""
    project = Path(project)
    target = project / "node_modules"
    if target.exists() or target.is_symlink():
        return False
    try:
        entry = entry_path(project, cache_root)
        if not (entry.is_dir() and (entry / COMPLETE).exists() and (entry / "node_modules").is_dir()):
            return False
        _clone(entry / "node_modules", target)
        return True
    except (OSError, subprocess.SubprocessError):
        shutil.rmtree(target, ignore_errors=True)  # a clone cut short must not look like an install
        return False


def store(project: Path, cache_root: Path | None = None) -> bool:
    """Cache `project`'s finished node_modules. True only when this call created the entry."""
    project = Path(project)
    source = project / "node_modules"
    root = Path(cache_root or CACHE_ROOT)
    try:
        entry = entry_path(project, root)
    except FileNotFoundError:
        return False
    if not source.is_dir() or (entry / COMPLETE).exists():
        return False
    tmp = None
    try:
        root.mkdir(parents=True, exist_ok=True)
        tmp = Path(tempfile.mkdtemp(prefix=".tmp-", dir=root))
        _clone(source, tmp / "node_modules")
        (tmp / COMPLETE).write_text("")
        try:
            os.rename(tmp, entry)  # atomic; fails if another store got there first, or a stale partial entry exists
        except OSError:
            if (entry / COMPLETE).exists():
                return False
            shutil.rmtree(entry, ignore_errors=True)  # a partial entry from a killed store: replace it
            os.rename(tmp, entry)
        tmp = None
        _prune(root)
        return True
    except (OSError, subprocess.SubprocessError):
        return False
    finally:
        if tmp is not None:
            shutil.rmtree(tmp, ignore_errors=True)


def npm_install(project: Path, cmd: list[str] | None = None, cache_root: Path | None = None, run=None,
                **kwargs) -> subprocess.CompletedProcess:
    """The one install call for every site: seed from the cache, run npm (it verifies a seeded tree and has little to
    write), then cache the result if it succeeded. Returns npm's own result, so callers check it as before."""
    project = Path(project)
    seed(project, cache_root)
    run = run or subprocess.run  # looked up per call, so a test that patches subprocess.run is honored
    proc = run(cmd or ["npm", "install", "--no-audit", "--no-fund"], cwd=project, **kwargs)
    if proc.returncode == 0:
        store(project, cache_root)
    return proc


def seed_tree(worktree: Path, cache_root: Path | None = None, depth: int = 2) -> list[Path]:
    """Seed every project (a dir with package-lock.json, at most `depth` levels down, never inside node_modules) in a
    fresh worktree, so the agent's own `npm install` finds its tree in place. Returns the dirs it seeded."""
    worktree = Path(worktree)
    seeded = []
    frontier = [worktree]
    for _ in range(depth + 1):
        nxt = []
        for d in frontier:
            if (d / LOCKFILE).is_file() and seed(d, cache_root):
                seeded.append(d)
            try:
                nxt += [c for c in d.iterdir() if c.is_dir() and not c.is_symlink()
                        and c.name != "node_modules" and not c.name.startswith(".")]
            except OSError:
                pass
        frontier = nxt
    return sorted(seeded)


def _prune(root: Path) -> None:
    entries = [d for d in root.iterdir() if d.is_dir() and not d.name.startswith(".") and (d / COMPLETE).exists()]
    entries.sort(key=lambda d: (d / COMPLETE).stat().st_mtime, reverse=True)
    for old in entries[KEEP:]:
        shutil.rmtree(old, ignore_errors=True)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("action", choices=["seed", "store"])
    ap.add_argument("project")
    ap.add_argument("--cache", default=None)
    args = ap.parse_args(argv)
    cache = Path(args.cache) if args.cache else None
    done = (seed if args.action == "seed" else store)(Path(args.project), cache)
    word = {"seed": ("seeded", "no cached install"), "store": ("stored", "nothing stored")}[args.action]
    print(word[0] if done else word[1])
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
