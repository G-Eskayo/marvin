"""MARVIN Term, draft 0.2: pixel source.

Thinner and cleaner, like a typewriter: one-pixel strokes (stroke to cap height 1:14, Courier territory) with slab
serifs drawn into each letter: feet on stems, flags on ascenders, beaks on E C S T Z and the c, s, z terminals.
Still a CRT dot-matrix underneath, and still carrying Atkinson Hyperlegible's legibility moves:
  - x-height 11 of cap 14, ascenders taller than caps
  - open apertures: c e s end straight instead of curling shut
  - I has full slabs, l a flag and a tail (no foot), 1 a flag and a foot, | plain and long
  - 0 narrow and slashed, O wide and round
  - b has a left foot, d a right foot (its tail), p a slab foot, q a kicked tail: none are mirrors
  - g hooks left, 9 drops a straight leg; rn never reads as m
Proportional. Format: char -> (top row, rows); row 0 sits on the baseline. '#' is a lit pixel.
(Draft 0.1, two-pixel strokes and no serifs, is in glyphs_v01.py.)
"""

