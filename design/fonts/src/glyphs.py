# ── accented Latin: each letter composed from its base and a mark, one clear row between them ───────────────
MARKS = {
    'acute': ["..#", ".#."],
    'grave': ["#..", ".#."],
    'circ':  [".#.", "#.#"],
    'diaer': ["#...#"],
    'tilde': [".##.#", "#.##."],
    'ring':  [".#.", "#.#", ".#."],
}
ACCENTED = {
    'á': ('a', 'acute'), 'à': ('a', 'grave'), 'â': ('a', 'circ'), 'ä': ('a', 'diaer'), 'ã': ('a', 'tilde'), 'å': ('a', 'ring'),
    'é': ('e', 'acute'), 'è': ('e', 'grave'), 'ê': ('e', 'circ'), 'ë': ('e', 'diaer'),
    'í': ('ı', 'acute'), 'ì': ('ı', 'grave'), 'î': ('ı', 'circ'), 'ï': ('ı', 'diaer'),
    'ó': ('o', 'acute'), 'ò': ('o', 'grave'), 'ô': ('o', 'circ'), 'ö': ('o', 'diaer'), 'õ': ('o', 'tilde'),
    'ú': ('u', 'acute'), 'ù': ('u', 'grave'), 'û': ('u', 'circ'), 'ü': ('u', 'diaer'),
    'ñ': ('n', 'tilde'), 'ý': ('y', 'acute'), 'ÿ': ('y', 'diaer'),
    'Á': ('A', 'acute'), 'À': ('A', 'grave'), 'Â': ('A', 'circ'), 'Ä': ('A', 'diaer'), 'Ã': ('A', 'tilde'), 'Å': ('A', 'ring'),
    'É': ('E', 'acute'), 'È': ('E', 'grave'), 'Ê': ('E', 'circ'), 'Ë': ('E', 'diaer'),
    'Í': ('I', 'acute'), 'Ì': ('I', 'grave'), 'Î': ('I', 'circ'), 'Ï': ('I', 'diaer'),
    'Ó': ('O', 'acute'), 'Ò': ('O', 'grave'), 'Ô': ('O', 'circ'), 'Ö': ('O', 'diaer'), 'Õ': ('O', 'tilde'),
    'Ú': ('U', 'acute'), 'Ù': ('U', 'grave'), 'Û': ('U', 'circ'), 'Ü': ('U', 'diaer'), 'Ñ': ('N', 'tilde'),
}
CEDILLA = ["..#.", "...#", ".##."]

def dotless_i(G):
    """ı: the i without its dot, so í ì î ï carry one mark, not a dot and a mark."""
    top, rows = G['i']
    keep = [r for k, r in enumerate(rows) if top - k <= 10]
    G['ı'] = (10, keep)

def _place(base_rows, mark, width):
    off = max(0, (width - len(mark[0])) // 2)
    return ["." * off + m + "." * (width - off - len(m)) for m in mark]

def add_accents(G):
    dotless_i(G)
    for ch, (base, mark) in ACCENTED.items():
        top, rows = G[base]
        w = len(rows[0]); m = MARKS[mark]
        if len(m[0]) > w:   # a mark wider than a narrow letter widens the glyph evenly
            pad = len(m[0]) - w; l = pad // 2
            rows = ["." * l + r + "." * (pad - l) for r in rows]; w = len(m[0])
        G[ch] = (top + 1 + len(m), _place(rows, m, w) + ["." * w] + rows)
    for ch, base in (('ç', 'c'), ('Ç', 'C')):
        top, rows = G[base]; w = len(rows[0])
        G[ch] = (top, rows + _place(rows, CEDILLA, w))

add_accents(G)
