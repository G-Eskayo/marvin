#!/usr/bin/env python3
"""
category_pass.py — detect disconnected nodes that share a category.

Reads brain-map/tree-data.json (generated by generate.py) and identifies pairs of
nodes that both belong to the same category (`cat` field) but have no direct synapse
edge between them.

Reasoning: nodes in the same conceptual category often have implicit coupling or
shared context — missing direct edges may indicate opportunities for explicit
collaboration, or undeclared dependencies that should be surfaced.

Algorithm:
  1. Walk tree, collect all nodes keyed by their `cat` field (skip nodes missing `cat`)
  2. For each category with ≥2 nodes, take combinations(sorted(ids), 2)
  3. For each pair, check for direct synapse edge
  4. Emit findings for pairs with no edge
  5. Tag findings with kind="category-match" for differentiation from sibling passes

Output: brain-map/reports/category-gaps.json + .md rollup
"""
from __future__ import annotations
import json
import os
import sys
import tempfile
from itertools import combinations
from pathlib import Path
from typing import TypedDict

HERE = Path(__file__).parent.parent
TREE_DATA_PATH = HERE / "tree-data.json"
OUTPUT_DIR = HERE / "reports"
OUTPUT_JSON = OUTPUT_DIR / "category-gaps.json"
OUTPUT_MD = OUTPUT_DIR / "category-gaps.md"


class Finding(TypedDict):
    kind: str
    category: str
    node_a: str
    node_b: str
    reason: str


def find_categories(tree: dict) -> dict[str, set[str]]:
    """Walk tree, collect all nodes keyed by their cat field. Skip nodes missing cat."""
    categories: dict[str, set[str]] = {}

    def walk(node: dict) -> None:
        cat = node.get("cat")
        node_id = node.get("id")

        # Only add if both cat and id are present and non-empty
        if cat and node_id:
            if cat not in categories:
                categories[cat] = set()
            categories[cat].add(node_id)

        # Recurse into children
        for child in node.get("children", []):
            walk(child)

    walk(tree)
    return categories


def has_direct_edge(node_a: str, node_b: str, synapses: list[dict]) -> bool:
    """Check if any synapse connects node_a and node_b (either direction)."""
    for synapse in synapses:
        a, b = synapse.get("a"), synapse.get("b")
        # Skip malformed entries (None, empty string)
        if not a or not b:
            continue
        if (a == node_a and b == node_b) or (a == node_b and b == node_a):
            return True
    return False


def find_gaps(tree: dict, synapses: list[dict]) -> list[Finding]:
    """Find pairs of same-category nodes with no direct edge."""
    categories = find_categories(tree)
    findings: list[Finding] = []

    for category, node_ids in categories.items():
        if len(node_ids) < 2:
            continue  # No pairs to check

        for node_a, node_b in combinations(sorted(node_ids), 2):
            if has_direct_edge(node_a, node_b, synapses):
                continue  # Skip pairs with direct edge

            findings.append(
                Finding(
                    kind="category-match",
                    category=category,
                    node_a=node_a,
                    node_b=node_b,
                    reason=f"both have cat='{category}' but have no synapse between each other",
                )
            )

    return sorted(findings, key=lambda f: (f["category"], f["node_a"], f["node_b"]))


def render_markdown(findings: list[Finding]) -> str:
    """Generate human-readable markdown report."""
    lines = [
        "# Category Gaps",
        "",
        f"Found {len(findings)} node pair(s) sharing a category but lacking direct synapse.",
        "",
    ]

    if not findings:
        lines.append("No gaps detected.")
        return "\n".join(lines)

    # Group by category for readability
    by_category: dict[str, list[Finding]] = {}
    for finding in findings:
        cat = finding["category"]
        if cat not in by_category:
            by_category[cat] = []
        by_category[cat].append(finding)

    for category in sorted(by_category.keys()):
        group = by_category[category]
        lines.append(f"## {category}")
        lines.append("")
        for finding in sorted(group, key=lambda f: (f["node_a"], f["node_b"])):
            lines.append(
                f"- **{finding['node_a']}** ↔ **{finding['node_b']}**: "
                f"{finding['reason']}"
            )
        lines.append("")

    return "\n".join(lines)


def main() -> None:
    if not TREE_DATA_PATH.exists():
        print(
            f"ERROR: {TREE_DATA_PATH} not found. Run brain-map/generate.py first.",
            file=sys.stderr,
        )
        sys.exit(1)

    data = json.loads(TREE_DATA_PATH.read_text(encoding="utf-8"))
    tree, synapses = data["tree"], data["synapses"]

    findings = find_gaps(tree, synapses)

    # Ensure output directory exists
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)

    # Write JSON atomically (temp file + replace) to guard against concurrent writes
    with tempfile.NamedTemporaryFile(
        mode="w",
        dir=OUTPUT_DIR,
        delete=False,
        suffix=".json",
        encoding="utf-8",
    ) as tmp:
        json.dump(findings, tmp, indent=2, ensure_ascii=False)
        tmp_path = tmp.name

    try:
        os.replace(tmp_path, OUTPUT_JSON)
    except OSError:
        # If replace fails (e.g., permissions), clean up temp and re-raise
        try:
            os.unlink(tmp_path)
        except OSError:
            pass
        raise

    # Write markdown (non-atomic, acceptable for the rollup)
    OUTPUT_MD.write_text(render_markdown(findings), encoding="utf-8")

    print(f"Found {len(findings)} category-match gap(s)")
    print(f"  JSON:  {OUTPUT_JSON}")
    print(f"  Markdown: {OUTPUT_MD}")


if __name__ == "__main__":
    main()
